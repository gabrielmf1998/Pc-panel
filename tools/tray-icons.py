#!/usr/bin/env python3
# Renders the four tray icons (normal, warning, serious, critical) to small ARGB32 images and
# writes tray/icons.h. The tray sends these images instead of icon names, so the colors show
# even when the tray host cached its icon lookups before the files were installed.
# Needs rsvg-convert (librsvg). Run it after changing an icon; the result is committed.
import os, struct, subprocess, sys, zlib

SIZES = (16, 22, 32, 48)
NAMES = ("pc-panel", "pc-panel-warning", "pc-panel-serious", "pc-panel-critical")
DIR = "share/icons/hicolor/scalable/apps"


def rgba(png):
    # minimal PNG reader for rsvg-convert output: 8 bit RGBA, not interlaced
    pos, idat, w = 8, b"", 0
    while pos < len(png):
        n, kind = struct.unpack(">I4s", png[pos:pos + 8])
        data = png[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, color, _, _, lace = struct.unpack(">IIBBBBB", data)
            assert depth == 8 and color == 6 and lace == 0, "unexpected PNG format"
        elif kind == b"IDAT":
            idat += data
        pos += 12 + n
    raw, stride, out, prev = zlib.decompress(idat), w * 4, bytearray(), bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b, c = prev[i], prev[i - 4] if i >= 4 else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    return w, h, out


def main():
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    lines = ["/* generated by tools/tray-icons.py from %s, do not edit */" % DIR,
             "#define ICON_SIZES %d" % len(SIZES), "static const int ICON_SIZE[ICON_SIZES] = {%s};" % ", ".join(map(str, SIZES))]
    tabela = []
    for k, nome in enumerate(NAMES):
        for s in SIZES:
            png = subprocess.run(["rsvg-convert", "-w", str(s), "-h", str(s), "-f", "png", "%s/%s.svg" % (DIR, nome)],
                                 check=True, capture_output=True).stdout
            w, h, px = rgba(png)
            assert (w, h) == (s, s)
            argb = bytearray()
            for i in range(0, len(px), 4):
                r, g, b, a = px[i:i + 4]
                argb += bytes((a, r, g, b))      # ARGB32 in network byte order, as the spec asks
            v = "icon_%d_%d" % (k, s)
            tabela.append(v)
            lines.append("static const unsigned char %s[%d] = {" % (v, len(argb)))
            for i in range(0, len(argb), 24):
                lines.append("    " + ",".join(str(x) for x in argb[i:i + 24]) + ",")
            lines.append("};")
    lines.append("static const unsigned char *const ICON_PX[4][ICON_SIZES] = {")
    for k in range(len(NAMES)):
        lines.append("    {%s}," % ", ".join(tabela[k * len(SIZES):(k + 1) * len(SIZES)]))
    lines.append("};")
    with open("tray/icons.h", "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main())
